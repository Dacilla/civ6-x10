"""Generated BRS/EPC compatibility data (Phase 8B.4).

Emits controller/X10/UI/X10BRSData.lua: the production registry as a Lua
table for the additive preview-compatibility layer
(controller/X10/UI/X10BRSCompat.lua). Same entries the native engine
consumes (minus REPEAT slot rows, which are not numerical effects);
the compat layer recomputes X10-effective arguments from these plus
live k/module resolution, then patches RMA's memoized cache.

Deterministic: sorted by (modifier_id, argument). Byte-stable for
identical registries.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Must match the native TransformKind order (X10Write.cpp kind ids).
NATIVE_KIND_ID = {"ADDITIVE": 0, "COMBAT": 1, "PROBABILITY": 2,
                  "DISCOUNT": 3, "VECTOR": 4, "DELTA": 5, "REPEAT": 6}

# Module bit order (must match production.MODULE_BITS insertion order).
MODULE_ORDER = ["traits", "policies", "governments", "pantheons", "wonders",
                "governors", "suzerain", "promotions", "dedications",
                "modes", "religion", "greatpeople", "projects"]


def _lua_str(s: str) -> str:
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"')


def build_brs_entries() -> list[dict]:
    """Non-REPEAT registry entries shaped for Lua emission."""
    from .bridge import collect_registry_rows
    from .production import build_production_registry
    entries, _ = build_production_registry(collect_registry_rows(ROOT))
    out = []
    for e in entries:
        if e["kind"] == "REPEAT":
            continue
        out.append({
            "id": e["modifier_id"],
            "arg": e["argument"],
            "official": e["official"],
            "kind": NATIVE_KIND_ID[e["kind"]],
            "countLike": 1 if e["count_like"] else 0,
            "owners": e["owners"],
        })
    out.sort(key=lambda r: (r["id"], r["arg"]))
    return out


def emit_lua(entries: list[dict]) -> str:
    lines = [
        "-- GENERATED by civ6x10.brsdata from the production registry.",
        "-- Do not hand-edit. Regenerate: python -m civ6x10 generate-brs-data",
        "-- REPEAT slot rows are excluded (not numerical effects).",
        "-- owners bitmask matches production.MODULE_BITS order:",
        "-- " + " ".join(f"{m}={1 << i}"
                         for i, m in enumerate(MODULE_ORDER)) + ".",
        "X10BRSData = {",
        "  kinds = { ADDITIVE = 0, COMBAT = 1, PROBABILITY = 2,"
        " DISCOUNT = 3, VECTOR = 4, DELTA = 5 },",
        "  entries = {",
    ]
    for e in entries:
        lines.append(
            "    { id = %s, arg = %s, official = %s, kind = %d,"
            " countLike = %d, owners = %d }," % (
                _lua_str(e["id"]), _lua_str(e["arg"]),
                _lua_str(e["official"]), e["kind"], e["countLike"],
                e["owners"]))
    lines.append("  }")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write_brs_data() -> Path:
    from .production import MODULE_BITS
    assert [MODULE_BITS[m] for m in MODULE_ORDER] == [1 << i for i in range(13)]
    path = ROOT / "controller" / "X10" / "X10BRSData.lua"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(emit_lua(build_brs_entries()), encoding="utf-8",
                    newline="\n")
    return path
